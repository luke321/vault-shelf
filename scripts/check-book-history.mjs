// design/0033
import assert from "node:assert/strict";
import { build } from "esbuild";
const output = await build({entryPoints:["src/core/index.ts"],bundle:true,write:false,format:"esm",platform:"node"});
const core = await import("data:text/javascript;base64,"+Buffer.from(output.outputFiles[0].text).toString("base64"));
const note=(id,date)=>({id,path:id+".md",title:id,folder:"Notes",date,tags:["acoustics","art"],people:[],props:{},body:"",excerpt:""});
const a=note("a","2020-01-01"),b=note("b","2020-02-01"),c=note("c","2026-01-01"),d=note("d","2020-03-01");
let settings=core.migrate({schema:10,wear:{"years/2020":7,"years/2026":20000,"old-shelf/gone":11}});
settings.shelves.find(s=>s.id==="years").hidden=true;
settings.shelves[0].picks=["years/2020"];
const reconcile=notes=>core.reconcileBookHistory(settings,core.buildLibrary(settings.shelves,notes,settings.noteOrder));
assert.equal(reconcile([a,b,c,a]).changed,true);
assert.equal(settings.wear["years/2020"],9);
assert.equal(settings.wear["years/2026"],20001);
assert.equal(settings.lastOpened["years/2020"],"never");
assert.equal(settings.lastOpened["old-shelf/gone"],"never");
assert.equal(settings.wear["old-shelf/gone"],11);
assert.equal(settings.wear["favourites/years/2020"],undefined);
assert.equal(settings.bookNotes["favourites/years/2020"],undefined);
assert.equal(settings.wear["tags/-plaque-A"],3);
const saved=JSON.stringify(settings);
settings=core.migrate(JSON.parse(saved));
assert.equal(reconcile([c,b,a]).changed,false);
assert.equal(JSON.stringify(settings),saved);
settings.wear["years/2020"]++;
settings.lastOpened["years/2020"]="2026-09-13T12:00:00.000Z";
reconcile([a,b,c,d]);
assert.equal(settings.wear["years/2020"],11);
assert.equal(settings.lastOpened["years/2020"],"2026-09-13T12:00:00.000Z");
reconcile([a,c,d]);
assert.equal(settings.wear["years/2020"],11);
assert.deepEqual(settings.bookNotes["years/2020"],["a","b","d"]);
reconcile([a,b,c,d]);
assert.equal(settings.wear["years/2020"],11);
reconcile([c]);
assert.deepEqual(settings.bookNotes["years/2020"],["a","b","d"]);
assert.equal(settings.wear["years/2020"],11);
reconcile([a,c]);
assert.equal(settings.wear["years/2020"],11);
const fav=settings.shelves[0];
fav.made={"-made-history":{name:"History",source:{kind:"all"}}};fav.picks.push("-made-history");
reconcile([a,b,c]);
assert.equal(settings.wear["favourites/-made-history"],3);
assert.equal(settings.lastOpened["favourites/-made-history"],"never");
const tags=settings.shelves.find(s=>s.id==="tags");tags.direction="manual";tags.order=["art","-untagged","acoustics"];
assert.equal(reconcile([a,b,c]).changed,false);
assert.equal(settings.wear["tags/-plaque-A"],4);
assert.deepEqual(core.migrate({lastOpened:{known:"never"},bookNotes:{good:["b","a","a"],bad:[1]}}).bookNotes,{good:["a","b"]});
assert.equal(core.migrate({lastOpened:{known:"never"}}).lastOpened.known,"never");
assert.deepEqual(core.migrate({wear:{big:50000,huge:1e30,zero:0,negative:-1,bad:Infinity}}).wear,{big:50000,huge:Number.MAX_SAFE_INTEGER,zero:0});
settings=core.emptySettings();reconcile([a,b,c]);
assert.equal(settings.wear["years/2020"],2);
assert.equal(settings.lastOpened["years/2020"],"never");
console.log("book history: legacy baseline, distinct notes, repeat/reload, additions/removal/re-addition, hidden sources, references, plaques, made books, explicit never, large counts and reset passed");
