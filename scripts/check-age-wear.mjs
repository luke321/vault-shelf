// design/0033
import assert from "node:assert/strict";
import { build } from "esbuild";
const output = await build({ entryPoints: ["src/core/index.ts"], bundle: true, write: false, format: "esm", platform: "node" });
const core = await import("data:text/javascript;base64," + Buffer.from(output.outputFiles[0].text).toString("base64"));
const today = "2026-09-13";
assert.deepEqual([null, "bad", "2027-01-01", "2025-09-14", "2025-09-13", "2023-09-14", "2023-09-13", "2019-09-14", "2019-09-13"].map(d => core.ageWearLevel(d, today)), [0,0,0,0,1,1,2,2,3]);
assert.equal(core.ageWearLevel("2020-02-29", "2021-02-28"),0);
assert.equal(core.ageWearLevel("2020-02-29", "2021-03-01"),1);
const note = (id,date) => ({id,path:id+".md",title:id,folder:"Journal",date,tags:["all"],people:[],props:{},body:"",excerpt:""});
const notes = [note("old","2010-01-01"), note("recent","2026-09-01"), note("undated",null)];
const settings=core.emptySettings();
settings.shelves[0].picks=["years/2010"];
settings.wear={"years/2010":2, "years/2026":12};
settings.bookSpines={"years/2010":"vellum"};
const saved=JSON.stringify(settings);
const views=core.buildLibrary(settings.shelves,notes,settings.noteOrder);
const before=JSON.stringify(views);
const age=core.buildAgeWear(views,today);
assert.equal(age["years/2010"],3);
assert.equal(age["years/2026"],0);
assert.equal(age["years/-undated"],0);
assert.equal(age["tags/all"],0);
assert.equal(age["favourites/years/2010"],3);
const oldBook=views.find(v=>v.shelf.id==="years").books.find(b=>b.key==="2010");
assert.equal(core.bookAgeWear({...oldBook,id:"years/-plaque-2010-2019"},today),3);
assert.deepEqual(core.buildAgeWear(core.buildLibrary(settings.shelves,notes.slice().reverse(),settings.noteOrder),today),age);
assert.equal(JSON.stringify(views),before);
assert.equal(JSON.stringify(settings),saved);
assert.equal(Math.max(age["years/2010"],core.wearLevel(settings.wear["years/2010"])),3);
assert.equal(Math.max(age["years/2026"],core.wearLevel(settings.wear["years/2026"])),3);
assert.deepEqual(core.migrate(settings).wear,settings.wear);
console.log("age wear: boundaries, leap day, fresh dates, active collection, undated, source parity, deterministic input order and unchanged settings passed");
